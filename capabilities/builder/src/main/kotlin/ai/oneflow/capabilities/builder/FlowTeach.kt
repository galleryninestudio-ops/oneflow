package ai.oneflow.capabilities.builder

import ai.oneflow.core.contracts.RiskTier
import kotlinx.serialization.Serializable

@Serializable
data class RecordedUiStep(
    val action: String,
    val targetRef: String,
    val label: String,
    val inputParamName: String? = null,
    val isSensitive: Boolean = false
)

@Serializable
data class CompiledFlowSkill(
    val skillId: String,
    val name: String,
    val parameters: List<String>,
    val riskTier: RiskTier,
    val requiredCapabilities: Set<String>,
    val flowCodeJs: String,
    val excludedSensitiveSteps: Int
)

/**
 * FlowTeach: compiles explicit user-recorded UI/tool steps into a parameterized FlowCode skill,
 * automatically stripping sensitive/password steps.
 */
object FlowTeachCompiler {
    fun compileToFlowCode(
        skillId: String,
        name: String,
        steps: List<RecordedUiStep>
    ): CompiledFlowSkill {
        var excluded = 0
        val safeSteps = steps.filter { step ->
            if (step.isSensitive) {
                excluded++
                false
            } else {
                true
            }
        }
        val params = safeSteps.mapNotNull { it.inputParamName }.distinct()
        val jsBody = buildString {
            appendLine("// Generated by Oneflow FlowTeach ($skillId)")
            appendLine("async function run(params) {")
            appendLine("  const snap = await flow.call('device.ui_tree', {});")
            for (step in safeSteps) {
                when (step.action.lowercase()) {
                    "tap", "click" -> {
                        appendLine("  await flow.call('device.tap_ref', { epoch: snap.epoch, refId: '${escapeJs(step.targetRef)}' });")
                    }
                    "input", "type" -> {
                        val argExpr = if (step.inputParamName != null) {
                            "String(params['${escapeJs(step.inputParamName)}'] || '')"
                        } else {
                            "''"
                        }
                        appendLine("  await flow.call('device.input_text', { epoch: snap.epoch, refId: '${escapeJs(step.targetRef)}', text: $argExpr });")
                    }
                    else -> {
                        appendLine("  // step: ${escapeJs(step.action)} -> ${escapeJs(step.label)}")
                    }
                }
            }
            appendLine("  return { ok: true, steps: ${safeSteps.size} };")
            appendLine("}")
        }
        return CompiledFlowSkill(
            skillId = skillId,
            name = name,
            parameters = params,
            riskTier = if (safeSteps.isNotEmpty()) RiskTier.EXTERNAL_SIDE_EFFECT else RiskTier.READ_ONLY,
            requiredCapabilities = if (safeSteps.isNotEmpty()) setOf("device.ui.read", "device.actuate") else setOf("device.ui.read"),
            flowCodeJs = jsBody,
            excludedSensitiveSteps = excluded
        )
    }

    private fun escapeJs(raw: String): String =
        raw.replace("\\", "\\\\").replace("'", "\\'")
}

@Serializable
data class AgentNativeActionContract(
    val actionId: String,
    val description: String,
    val riskTier: RiskTier,
    val idempotent: Boolean
)

@Serializable
data class AgentNativeAppManifest(
    val appId: String,
    val name: String,
    val sdkVersion: String = "0.6.0",
    val actions: List<AgentNativeActionContract>
)

object AgentNativeAppSdk {
    fun scaffoldManifest(
        appId: String,
        name: String,
        actions: List<AgentNativeActionContract>
    ): AgentNativeAppManifest = AgentNativeAppManifest(
        appId = appId,
        name = name,
        actions = actions
    )
}
